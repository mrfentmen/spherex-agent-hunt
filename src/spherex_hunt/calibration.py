"""Calibration data generator. TEST DATA ONLY.

Builds a synthetic detection table with known ground truth:
- one moving object on a straight line (the planted target),
- stationary stars (zero motion),
- single-epoch glitches (elongated, should be excluded as artifacts),
- random field noise detections.

Its only jobs: prove the pipeline finds what it should, kills what it
should, and calibrate tolerances. It is never presented as real data;
every file it writes carries a header comment saying so.
"""
from __future__ import annotations

import csv
import math
import random

FIELDS = ["source_id", "epoch_id", "mjd", "ra_deg", "dec_deg", "snr",
          "flux", "roundness", "pixel_area", "x_px", "y_px", "image_id",
          "band", "flux_band"]

EPOCH_MJDS = [60800.0, 60801.0, 60802.0, 60804.0]


def generate(path: str, seed: int = 3301) -> dict:
    rng = random.Random(seed)
    rows: list[dict] = []

    def add(sid, ep_i, ra, dec, snr, flux, rnd, area, band_flux=None):
        rows.append({
            "source_id": sid, "epoch_id": f"epoch_{ep_i + 1}",
            "mjd": EPOCH_MJDS[ep_i], "ra_deg": f"{ra:.6f}",
            "dec_deg": f"{dec:.6f}", "snr": f"{snr:.1f}",
            "flux": f"{flux:.1f}", "roundness": f"{rnd:.2f}",
            "pixel_area": f"{area:.1f}",
            "x_px": f"{rng.uniform(0, 2040):.1f}",
            "y_px": f"{rng.uniform(0, 2040):.1f}",
            "image_id": f"CAL-ONLY-{ep_i + 1}",
            "band": "SPHEREx-D2" if band_flux is not None else "",
            "flux_band": f"{band_flux:.1f}" if band_flux is not None else "",
        })

    # Planted mover: 30 arcsec/day across the patch diagonal.
    ra0, dec0 = 210.8000, 54.3500
    vra = 30.0 / 3600.0 / math.cos(math.radians(dec0))  # deg/day in RA
    vdec = 12.0 / 3600.0
    for i, mjd in enumerate(EPOCH_MJDS):
        dt = mjd - EPOCH_MJDS[0]
        add("PLANTED-MOVER", i,
            ra0 + vra * dt + rng.uniform(-0.00005, 0.00005),
            dec0 + vdec * dt + rng.uniform(-0.00005, 0.00005),
            snr=25.0, flux=900.0, rnd=0.08, area=12.0,
            band_flux=900.0 + rng.uniform(-20, 20))

    # Stationary stars: same position every epoch.
    for s in range(6):
        ra = 210.79 + rng.uniform(0, 0.02)
        dec = 54.34 + rng.uniform(0, 0.02)
        for i in range(len(EPOCH_MJDS)):
            add(f"STAR-{s}", i, ra + rng.uniform(-0.00002, 0.00002),
                dec + rng.uniform(-0.00002, 0.00002),
                snr=40.0, flux=2000.0, rnd=0.05, area=14.0)

    # Single-epoch glitches: elongated, in one epoch only.
    for gnum in range(4):
        add(f"GLITCH-{gnum}", rng.randrange(len(EPOCH_MJDS)),
            210.795 + rng.uniform(0, 0.015), 54.345 + rng.uniform(0, 0.015),
            snr=8.0, flux=300.0, rnd=0.9, area=90.0)

    # Field noise: random single detections.
    for n in range(12):
        add(f"NOISE-{n}", rng.randrange(len(EPOCH_MJDS)),
            210.79 + rng.uniform(0, 0.03), 54.34 + rng.uniform(0, 0.03),
            snr=6.0, flux=120.0, rnd=0.3, area=8.0)

    with open(path, "w", newline="") as fh:
        fh.write("# CALIBRATION DATA - synthetic, generated by "
                 "spherex_hunt.calibration. Not real observations.\n")
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        w.writeheader()
        w.writerows(rows)
    return {"rows": len(rows), "planted_mover": "PLANTED-MOVER",
            "epochs": len(EPOCH_MJDS)}


def load_calibration(path: str):
    """Load a calibration CSV (skips the comment line)."""
    from .detections import load_detections
    with open(path) as fh:
        lines = [ln for ln in fh if not ln.startswith("#")]
    tmp = path + ".clean.csv"
    with open(tmp, "w") as fh:
        fh.writelines(lines)
    return load_detections(tmp)
